#!/usr/bin/env python3
"""T-068 opt-in Skia hard-brush screen against Godot-generated coverage.

This is deliberately *not* a production raster backend or native C++ timing.
The canonical fixture is generated by the actual DrawingEditSession with far
signed anchors and includes separate coverage for no-op alpha-zero gestures.
We independently reconstruct its straight-RGBA8 result before testing Skia.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import statistics
import time
from pathlib import Path
from typing import Any, NotRequired, TypedDict

from t068_cairo_cpu import RGBA, fixture, source_over
from t068_skia_cpu import SkiaCPU, verify_wheel

ROOT = Path(__file__).resolve().parents[2]
ORACLE_FILE = ROOT / "tools/benchmarks/t068_skia_brush_oracle.json"


class BrushSpec(TypedDict):
    id: str
    path: list[list[float]]
    transform: NotRequired[list[float]]
    view_path: NotRequired[list[list[float]]]
    width: float
    paint: list[int]
    erase: bool
    selection: str
    coverage_indices: list[int]
    changed_indices: list[int]
    after_sha256: str


def _allowed(index: int, side: int, kind: str) -> bool:
    """Mirror only DrawingSelection's declared rectangular/sparse predicate.

    The *coverage* comes from Godot, not this helper. Masks are pixel-local,
    not a claim about a Skia native clipping API or transformed quad scopes.
    """
    x, y = index % side, index // side
    inside = 8 <= x < 24 and 8 <= y < 24
    if kind == "none":
        return True
    if kind == "rect":
        return inside
    if kind == "sparse":
        return inside and (x + y) % 3 == 0
    if kind == "inverted":
        return not inside
    raise ValueError(f"Unknown oracle selection: {kind}")


def canonical_pixels(source: bytes, coverage: set[int], paint: RGBA,
                     erase: bool) -> bytes:
    """Oracle-blend once against the original source, preserving hidden RGB."""
    output = bytearray(source)
    for index in coverage:
        offset = index * 4
        previous = source[offset:offset + 4]
        value = (0, 0, 0, 0) if erase else source_over(paint, tuple(previous))
        output[offset:offset + 4] = bytes(value)
    return bytes(output)


def raster_path(case: BrushSpec) -> list[list[float]]:
    """Inverse-map frozen view samples to local raster space, not signed world.

    The view matrix is serialized as [xx, xy, yx, yy, tx, ty]. With no
    transform the original local path is the tested identity baseline.
    Explicit view samples are required for non-identity matrices; we never
    silently assume a transformed gesture was issued in local coordinates.
    """
    transform = case.get("transform")
    if transform is None:
        if "view_path" in case:
            raise ValueError(f"Unexpected view path without transform: {case['id']}")
        return case["path"]
    if (not isinstance(transform, list) or len(transform) != 6
            or any(type(value) not in (float, int) or not -1000 <= value <= 1000
                   for value in transform)):
        raise ValueError(f"Invalid view transform: {case['id']}")
    xx, xy, yx, yy, tx, ty = transform
    determinant = xx * yy - yx * xy
    if abs(determinant) < 0.001:
        raise ValueError(f"Singular view transform: {case['id']}")
    view_path = case.get("view_path")
    if (not isinstance(view_path, list) or len(view_path) != len(case["path"])
            or any(not isinstance(point, list) or len(point) != 2
                   or any(type(v) not in (int, float) or not -2000 <= v <= 2000 for v in point)
                   for point in view_path)):
        raise ValueError(f"Invalid transformed view path: {case['id']}")
    local = [[(yy * (x - tx) - yx * (y - ty)) / determinant,
              (xx * (y - ty) - xy * (x - tx)) / determinant]
             for x, y in view_path]
    if any(abs(a - b) > 0.00001 for actual, pinned in zip(local, case["path"])
           for a, b in zip(actual, pinned)):
        raise ValueError(f"View path does not invert to pinned raster path: {case['id']}")
    return local


def _sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def load_oracle(path: Path = ORACLE_FILE) -> tuple[int, bytes, list[BrushSpec]]:
    """Fail closed on missing/corrupt/duplicate or inconsistent fixture data.

    Each case is independently checked against the Python compositing oracle
    before any Skia result is considered, including no-ops and hidden colors.
    """
    payload = json.loads(path.read_text(encoding="utf-8"))
    side = payload["side"]
    if payload["schema"] != 2 or side != 32 or payload["source"] != "t068_cairo_cpu.fixture(side, False)":
        raise ValueError("Unsupported Godot brush fixture schema or side")
    if payload["anchor_x"] != "9007199254740993" or payload["anchor_y"] != "-9007199254740993":
        raise ValueError("Fixture lacks tested signed anchor")
    if "drawing_t068_skia_brush_oracle.gd" not in payload["generator"]:
        raise ValueError("Fixture generator identity is missing")
    source = fixture(side, False)
    if _sha(source) != payload["source_sha256"]:
        raise ValueError("Fixture source does not match canonical RGBA8 bytes")
    cases: list[BrushSpec] = payload["cases"]
    if len(cases) != 16 or len({case["id"] for case in cases}) != len(cases):
        raise ValueError("Fixture cases are missing or duplicated")
    for case in cases:
        paint = case["paint"]
        path_points = case["path"]
        if (not path_points or len(paint) != 4 or any(type(v) is not int or not 0 <= v <= 255 for v in paint)
                or not 0 < case["width"] <= side or case["selection"] not in ("none", "rect", "sparse", "inverted")
                or any(len(point) != 2 or not all(0 <= coord <= side for coord in point) for point in path_points)):
            raise ValueError(f"Invalid brush case: {case['id']}")
        raster_path(case)  # Validate every transform and view/local-path pair.
        coverage = case["coverage_indices"]
        changed = case["changed_indices"]
        for indices in (coverage, changed):
            if indices != sorted(set(indices)) or any(type(i) is not int or not 0 <= i < side * side for i in indices):
                raise ValueError(f"Out of range, unordered or repeated pixel index: {case['id']}")
        if any(not _allowed(i, side, case["selection"]) for i in coverage):
            raise ValueError(f"Godot coverage exceeds selected area: {case['id']}")
        color: RGBA = tuple(paint)  # type: ignore[assignment]
        expected = canonical_pixels(source, set(coverage), color, case["erase"])
        really_changed = [i for i in range(side * side) if source[i * 4:i * 4 + 4] != expected[i * 4:i * 4 + 4]]
        if really_changed != changed or _sha(expected) != case["after_sha256"]:
            raise ValueError(f"Independent RGBA8 oracle disagrees with Godot: {case['id']}")
    pair = {case["id"]: case for case in cases}
    if not pair["self_crossing"]["coverage_indices"] == pair["self_crossing_batched"]["coverage_indices"]:
        raise ValueError("Godot's continuous and batched stroke coverage disagrees")
    if pair["zero_alpha_noop"]["changed_indices"]:
        raise ValueError("Godot's alpha-zero source-over altered original pixels")
    transformed = {case["id"] for case in cases if "transform" in case}
    if transformed != {"zoom_pan_rect", "rotation90_inverted", "mirrored_crossing",
                       "nonuniform_sparse", "shear_erase"}:
        raise ValueError("Expected transformed brush cases are missing")
    return side, source, cases


def _draw_stroke(canvas: Any, skia: Any, points: list[list[float]], width: float,
                 paint: Any) -> None:
    """Draw one Skia shape for the whole gesture to avoid reblending overlaps."""
    if len(points) == 1:
        canvas.drawCircle(float(points[0][0]), float(points[0][1]), width / 2, paint)
    else:
        path = skia.Path()
        path.moveTo(*points[0])
        for point in points[1:]:
            path.lineTo(*point)
        canvas.drawPath(path, paint)


def _stroke_paint(skia: Any, case: BrushSpec, coverage: bool) -> Any:
    brush = skia.Paint(AntiAlias=False)
    if coverage:
        brush.setColor(skia.ColorWHITE)
        brush.setBlendMode(skia.BlendMode.kSrc)
    else:
        brush.setColor4f(skia.Color4f(*(v / 255.0 for v in case["paint"])))
        brush.setBlendMode(skia.BlendMode.kClear if case["erase"] else skia.BlendMode.kSrcOver)
    if len(case["path"]) > 1:
        brush.setStyle(skia.Paint.kStroke_Style)
        brush.setStrokeWidth(case["width"])
        brush.setStrokeCap(skia.Paint.kRound_Cap)
        brush.setStrokeJoin(skia.Paint.kRound_Join)
    return brush


def skia_coverage(renderer: SkiaCPU, side: int, case: BrushSpec) -> tuple[set[int], float]:
    skia = renderer.skia
    image = skia.ImageInfo.Make(side, side, skia.ColorType.kAlpha_8_ColorType,
                                skia.AlphaType.kPremul_AlphaType)
    data = bytearray(side * side)
    surface = skia.Surface.MakeRasterDirect(image, data, side)
    if surface is None:
        raise RuntimeError("Skia rejected hard brush A8 mask")
    # Exclude the Python view-to-raster conversion from the draw-only timer.
    local_path = raster_path(case)
    start = time.perf_counter_ns()
    _draw_stroke(surface.getCanvas(), skia, local_path, case["width"],
                 _stroke_paint(skia, case, True))
    elapsed_us = (time.perf_counter_ns() - start) / 1000.0
    if any(value not in (0, 255) for value in data):
        raise AssertionError("Skia non-antialiased brush mask contains fractional alpha")
    return {i for i, value in enumerate(data) if value and _allowed(i, side, case["selection"])}, elapsed_us


def skia_direct(renderer: SkiaCPU, source: bytes, side: int,
                case: BrushSpec) -> tuple[bytes, float]:
    skia = renderer.skia
    data = bytearray(source)
    surface = renderer._surface(data, side, side, premul=False)
    # Exclude the Python view-to-raster conversion from the draw-only timer.
    local_path = raster_path(case)
    start = time.perf_counter_ns()
    _draw_stroke(surface.getCanvas(), skia, local_path, case["width"],
                 _stroke_paint(skia, case, False))
    elapsed_us = (time.perf_counter_ns() - start) / 1000.0
    # This explicitly simulates a *post* pixel-selection pass in Python;
    # Skia did NOT process DrawingSelection or its inverted/sparse rules.
    for i in range(side * side):
        if not _allowed(i, side, case["selection"]):
            data[i * 4:i * 4 + 4] = source[i * 4:i * 4 + 4]
    return bytes(data), elapsed_us


def _pixel_mismatch(actual: bytes, expected: bytes) -> int:
    if len(actual) != len(expected):
        raise ValueError("RGBA8 buffer length mismatch")
    return sum(actual[i:i + 4] != expected[i:i + 4] for i in range(0, len(actual), 4))


def screen(renderer: SkiaCPU, trials: int = 7,
           oracle_path: Path = ORACLE_FILE) -> dict[str, object]:
    if trials < 1 or trials > 50:
        raise ValueError("Skia brush trial count must be between 1 and 50")
    side, source, cases = load_oracle(oracle_path)
    output: list[dict[str, object]] = []
    for case in cases:
        expected_coverage = set(case["coverage_indices"])
        expected = canonical_pixels(source, expected_coverage, tuple(case["paint"]), case["erase"])  # type: ignore[arg-type]
        mask_us: list[float] = []
        direct_us: list[float] = []
        first: tuple[set[int], bytes] | None = None
        for _ in range(trials):
            coverage, mask_elapsed = skia_coverage(renderer, side, case)
            direct, draw_elapsed = skia_direct(renderer, source, side, case)
            if first is not None and (coverage, direct) != first:
                raise AssertionError(f"Skia is nondeterministic: {case['id']}")
            first = coverage, direct
            mask_us.append(mask_elapsed)
            direct_us.append(draw_elapsed)
        assert first is not None
        coverage, direct = first
        # This is only a diagnostic: a Python canonical compositor over Skia's
        # shape mask. It avoids blend losses but cannot fix coverage differences.
        stencil = canonical_pixels(source, coverage, tuple(case["paint"]), case["erase"])  # type: ignore[arg-type]
        if any(direct[i * 4:i * 4 + 4] != source[i * 4:i * 4 + 4]
               for i in range(side * side) if i not in coverage):
            raise AssertionError(f"Direct Skia modified pixels outside its non-AA mask: {case['id']}")
        output.append({
            "id": case["id"], "paint_alpha": case["paint"][3],
            "view_transform": case.get("transform", [1, 0, 0, 1, 0, 0]),
            "erase": case["erase"], "selection": case["selection"],
            "godot_covered": len(expected_coverage), "skia_covered": len(coverage),
            "missing_godot_coverage": len(expected_coverage - coverage),
            "extra_skia_coverage": len(coverage - expected_coverage),
            "direct_rgba8_mismatched_pixels": _pixel_mismatch(direct, expected),
            "skia_mask_plus_canonical_blend_mismatched_pixels": _pixel_mismatch(stencil, expected),
            "skia_mask_median_us": round(statistics.median(mask_us), 3),
            "skia_direct_draw_median_us": round(statistics.median(direct_us), 3),
            "trials": trials,
        })
    return {
        "ticket": "T-068", "godot_fixture_sha256": _sha(oracle_path.read_bytes()),
        "skia_version": renderer.version, "oracle": str(oracle_path.relative_to(ROOT)) if oracle_path.is_relative_to(ROOT) else oracle_path.name,
        "scope": "Skia raster-local hard-path coverage including inverse-transformed view paths, postmasked direct RGBA8 and oracle blending; no native C++ or physical timing",
        "warnings": [
            "Godot fixture is authoritative for hard brush, once coverage, selection, signed anchor and unchanged hidden RGB",
            "Skia selections are post-processed in Python, not implemented as native clip masks",
            "View transforms are inverted in Python before drawing; this does not test native Godot/Skia marshaling",
            "Skia shape and blend discrepancies are research results; no automatic change to canonical Drawing pixels",
            "Python shape timings exclude surface creation, selection and Godot/GDExtension publication",
        ],
        "cases": output,
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--wheel", type=Path, required=True)
    parser.add_argument("--oracle", type=Path, default=ORACLE_FILE)
    parser.add_argument("--trials", type=int, default=7)
    parser.add_argument("--runs", type=int, choices=(1, 2, 3), default=2)
    parser.add_argument("--output", type=Path)
    args = parser.parse_args()
    verify_wheel(args.wheel)
    runs = [screen(SkiaCPU(), args.trials, args.oracle) for _ in range(args.runs)]
    data = {"ticket": "T-068", "runs": runs}
    if args.output:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8")
    count = sum(len(run["cases"]) for run in runs)
    coverage_mismatch = sum(bool(c["missing_godot_coverage"] or c["extra_skia_coverage"])
                            for run in runs for c in run["cases"])
    pixel_mismatch = sum(bool(c["direct_rgba8_mismatched_pixels"])
                         for run in runs for c in run["cases"])
    print(f"T068_SKIA_BRUSH_SCREEN_PASSED: {count} Godot brush/mask comparisons; "
          f"{coverage_mismatch} coverage discrepancies; {pixel_mismatch} direct RGBA8 disparities")


if __name__ == "__main__":
    main()
